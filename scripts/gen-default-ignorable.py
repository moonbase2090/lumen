#!/usr/bin/env python3
"""Generate the Default_Ignorable_Code_Point table for lumen-track0.

The table is not written by hand: it comes from the Unicode Character Database
file DerivedCoreProperties.txt, pinned to one version and one SHA-256.

usage:
    gen-default-ignorable.py [--check] PATH_TO_DerivedCoreProperties.txt

Get the pinned file with:
    curl -O https://www.unicode.org/Public/16.0.0/ucd/DerivedCoreProperties.txt

It refuses any file that is not the pinned version with the pinned digest. It
writes, under crates/lumen-track0:
    data/default-ignorable-16.0.0.txt   the property's lines, copied unchanged
    src/default_ignorable.rs            the same ranges as a Rust table
With --check it writes nothing and exits 1 if either file differs from what it
would write, so a CI job or a reviewer can prove the committed files match the
pinned data. The crate's tests then check the table against the data file for
every code point.
"""
import hashlib
import pathlib
import re
import sys

VERSION = "16.0.0"
SHA256 = "39d35161f2954497f69e08bdb9e701493f476a3d30222de20028feda36c1dabd"
URL = f"https://www.unicode.org/Public/{VERSION}/ucd/DerivedCoreProperties.txt"
PROPERTY = "Default_Ignorable_Code_Point"

ROOT = pathlib.Path(__file__).resolve().parent.parent / "crates" / "lumen-track0"
DATA = ROOT / "data" / f"default-ignorable-{VERSION}.txt"
TABLE = ROOT / "src" / "default_ignorable.rs"

LINE = re.compile(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*" + PROPERTY + r"\b")


def main() -> int:
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv[1:]
    if len(args) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    raw = pathlib.Path(args[0]).read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    text = raw.decode("utf-8")
    first = text.splitlines()[0]
    if first != f"# DerivedCoreProperties-{VERSION}.txt" or digest != SHA256:
        print(f"not the pinned file: header {first!r}, sha256 {digest}", file=sys.stderr)
        return 2
    lines = [l for l in text.splitlines() if LINE.match(l)]
    ranges = []
    for l in lines:
        m = LINE.match(l)
        lo = int(m.group(1), 16)
        hi = int(m.group(2), 16) if m.group(2) else lo
        if ranges and lo == ranges[-1][1] + 1:
            ranges[-1] = (ranges[-1][0], hi)
        else:
            ranges.append((lo, hi))
    data = (
        f"# {PROPERTY} from DerivedCoreProperties-{VERSION}.txt\n"
        f"# Source: {URL}\n"
        f"# SHA-256 of that file: {SHA256}\n"
        "# These are its lines for the property, copied unchanged by\n"
        "# scripts/gen-default-ignorable.py. Do not edit.\n"
        + "\n".join(lines)
        + "\n"
    )
    body = "".join(f"    (0x{lo:04X}, 0x{hi:04X}),\n" for lo, hi in ranges)
    table = (
        f"//! The `{PROPERTY}` ranges of Unicode {VERSION}.\n"
        "//!\n"
        f"//! Generated by `scripts/gen-default-ignorable.py` from the pinned\n"
        f"//! `DerivedCoreProperties.txt` (SHA-256 {SHA256}). Do not edit: change the\n"
        "//! generator and run it again. A test checks this table against\n"
        f"//! `data/default-ignorable-{VERSION}.txt` for every code point.\n"
        "\n"
        "/// The inclusive ranges, in order, with adjacent ranges joined.\n"
        "pub(crate) const RANGES: &[(u32, u32)] = &[\n" + body + "];\n"
    )
    if check:
        ok = DATA.read_text() == data and TABLE.read_text() == table
        print("up to date" if ok else "OUT OF DATE: run the generator", file=sys.stderr if not ok else sys.stdout)
        return 0 if ok else 1
    DATA.write_text(data)
    TABLE.write_text(table)
    print(f"wrote {DATA.relative_to(ROOT.parent.parent)} ({len(lines)} lines) and {TABLE.relative_to(ROOT.parent.parent)} ({len(ranges)} ranges)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
